package dev.railroadide.railroad.ui.styling;

/** Semantic appearance presets mapped to CSS classes by Railroad buttons. */
public enum ButtonVariant {
    /** Accent styling for the main action. */
    PRIMARY,
    /** Lower-emphasis styling for supporting actions. */
    SECONDARY,
    /** Minimal background styling for unobtrusive actions. */
    GHOST,
    /** Danger styling for destructive actions. */
    DANGER,
    /** Success styling for positive actions. */
    SUCCESS,
    /** Warning styling for actions requiring attention. */
    WARNING
}
