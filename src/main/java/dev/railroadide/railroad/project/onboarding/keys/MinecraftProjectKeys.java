package dev.railroadide.railroad.project.onboarding.keys;

/**
 * Context keys for Minecraft versions, mappings, and mod identity.
 */
public class MinecraftProjectKeys {
    /**
     * Key for the selected Minecraft version.
     */
    public static final String MINECRAFT_VERSION = "minecraft.version";
    /**
     * Key for the mod identifier used in metadata and generated resources.
     */
    public static final String MOD_ID = "minecraft.modId";
    /**
     * Key for the human-readable mod name.
     */
    public static final String MOD_NAME = "minecraft.modName";
    /**
     * Key for the selected Minecraft mapping channel.
     */
    public static final String MAPPING_CHANNEL = "minecraft.mappingChannel";
    /**
     * Key for the version of the selected mappings.
     */
    public static final String MAPPING_VERSION = "minecraft.mappingVersion";
    /**
     * Key for the generated main class name.
     */
    public static final String MAIN_CLASS = "minecraft.mainClass";
}
